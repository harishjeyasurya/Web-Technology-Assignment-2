-- 1. CREATE DATABASE ---------------------------------------------------
-- Drop the old copy (if any) so the script can be re-run safely.
DROP DATABASE IF EXISTS student_portal;
-- utf8mb4 supports every character (Tamil names, emojis, etc.).
CREATE DATABASE student_portal
CHARACTER SET utf8mb4
COLLATE utf8mb4_general_ci;
-- Select the new database for all following statements.
USE student_portal;

-- 2. TABLE : students ---------------------------------------------------
-- Stores one row per registered student.
CREATE TABLE students (
student_id INT AUTO_INCREMENT, -- unique id generated by MySQL
name VARCHAR(100) NOT NULL, -- full name of the student
roll_number VARCHAR(20) NOT NULL, -- e.g. 24CS077 (must be unique)
email VARCHAR(100) NOT NULL, -- login / contact e-mail (unique)
password VARCHAR(64) NOT NULL, -- SHA-256 hash (64 hex chars), never plain text
course VARCHAR(100) NOT NULL, -- selected course from dropdown
mobile CHAR(10) NOT NULL, -- exactly 10 digits
gender ENUM('Male','Female','Other') NOT NULL,
address TEXT NOT NULL, -- postal address
profile_image VARCHAR(255) NOT NULL, -- relative path e.g. uploads/images/1728_photo.jpg
created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,-- set automatically on insert
-- 3. PRIMARY KEY
CONSTRAINT pk_students PRIMARY KEY (student_id),
-- UNIQUE keys stop duplicate roll numbers / e-mails at database level
CONSTRAINT uq_students_roll UNIQUE (roll_number),
CONSTRAINT uq_students_email UNIQUE (email)
) ENGINE = InnoDB; -- InnoDB is required for foreign keys
-- TABLE : student_files ------------------------------------------------
-- Stores the METADATA of every uploaded document / image.
-- The real file lives on disk inside the uploads/ folder.
CREATE TABLE student_files (
file_id INT AUTO_INCREMENT, -- unique id of the file
student_id INT NOT NULL, -- owner of the file
file_name VARCHAR(255) NOT NULL, -- stored (timestamped) file name
file_path VARCHAR(255) NOT NULL, -- relative path e.g. uploads/documents/x.pdf
file_type VARCHAR(50) NOT NULL, -- MIME type e.g. application/pdf, image/png
upload_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP, -- set automatically on upload
CONSTRAINT pk_student_files PRIMARY KEY (file_id),
-- 4. FOREIGN KEY : each file belongs to one student.
-- ON DELETE CASCADE removes the file rows when the student is deleted.
CONSTRAINT fk_files_student FOREIGN KEY (student_id)
REFERENCES students (student_id)
ON DELETE CASCADE
ON UPDATE CASCADE
) ENGINE = InnoDB;
-- TABLE : admin --------------------------------------------------------
-- Login accounts for the Servlet portal (session based login).
CREATE TABLE admin (
admin_id INT AUTO_INCREMENT,
username VARCHAR(50) NOT NULL,
password VARCHAR(64) NOT NULL, -- SHA-256 hash of the password
full_name VARCHAR(100) NOT NULL,
CONSTRAINT pk_admin PRIMARY KEY (admin_id),
CONSTRAINT uq_admin_username UNIQUE (username)
) ENGINE = InnoDB;
